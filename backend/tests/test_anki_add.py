"""Cards go through the Anki Manager gateway so its card rules apply. AnkiConnect and the gateway are mocked."""
import pytest

from app.schemas.anki import SentenceCardRequest, VocabCardRequest
from app.services import anki_service as anki_module
from app.services.anki_service import anki_service


@pytest.fixture
def fake_anki(monkeypatch):
    """Read-only AnkiConnect fake; `dup` controls the duplicate precheck."""
    state = {"dup": False, "calls": []}

    def invoke(action, **params):
        state["calls"].append(action)
        if action == "version":
            return 6
        if action == "canAddNotesWithErrorDetail":
            if state["dup"]:
                return [{"canAdd": False, "error": "cannot create note because it is a duplicate"}]
            return [{"canAdd": True}]
        if action == "addTags":
            return None
        raise AssertionError(f"unexpected direct AnkiConnect call: {action}")

    monkeypatch.setattr(anki_service, "invoke", invoke)
    return state


@pytest.fixture
def gateway(monkeypatch):
    sent = []

    class Resp:
        status_code = 200

        def __init__(self, body):
            self._body = body

        def raise_for_status(self):
            pass

        def json(self):
            return self._body

    def post(url, json, timeout):
        sent.append((url, json))
        return Resp({"success": True, "note_id": 123, "duplicate": False})

    monkeypatch.setattr(anki_module.requests, "post", post)
    return sent


def test_sentence_goes_through_gateway(fake_anki, gateway):
    res = anki_service.add_sentence_card(SentenceCardRequest(sentence="I agree.", translation="동의한다."))
    assert res.success and res.note_id == 123
    url, body = gateway[0]
    assert url.endswith("/api/cards/sentence")
    assert body["sentence"] == "I agree." and body["translation"] == "동의한다."
    assert "addNote" not in fake_anki["calls"]


@pytest.mark.anyio
async def test_vocab_sends_only_word_meaning_pos(fake_anki, gateway):
    res = anki_service.add_vocab_card(VocabCardRequest(
        word="stem from something", meaning="~에서 유래하다/기인하다", pos="prep",
        synonyms="originate from", example="Ex.", explanation="3-step explanation"))
    assert res.success
    url, body = gateway[0]
    assert url.endswith("/api/cards/vocab")
    assert body["word"] == "stem from A"
    assert "/" not in body["meaning"] and body["meaning"] == "~에서 유래하다, 기인하다"
    assert body["pos"] == ""  # prep is not an allowed POS in Anki Manager
    # Example and explanation are generated by the gateway under its own rules.
    assert body.get("synonyms", "") == "" and body.get("example", "") == "" and body.get("explanation", "") == ""
    assert body["auto_enrich"] is True


def test_duplicate_never_reaches_gateway(fake_anki, gateway):
    fake_anki["dup"] = True
    res = anki_service.add_sentence_card(SentenceCardRequest(sentence="He used to be healthy.", translation="t"))
    assert res.success and res.duplicate
    assert gateway == []


def test_gateway_down_is_an_error_not_a_direct_write(fake_anki, monkeypatch):
    def post(*a, **k):
        raise anki_module.requests.exceptions.ConnectionError("refused")
    monkeypatch.setattr(anki_module.requests, "post", post)
    res = anki_service.add_sentence_card(SentenceCardRequest(sentence="I agree.", translation="t"))
    assert not res.success and "Anki Manager" in res.error
    assert "addNote" not in fake_anki["calls"]


# ---------- grammar cards ----------

from app.schemas.anki import GrammarCardRequest  # noqa: E402


def test_grammar_card_sends_my_mistake_as_a_wrong_option(fake_anki, gateway):
    res = anki_service.add_grammar_card(GrammarCardRequest(
        sentence="I am looking forward to meeting you.", answer="meeting", mistake="meet"))
    assert res.success and res.note_id == 123
    url, body = gateway[0]
    assert url.endswith("/api/cards/grammar")
    assert body["sentence"] == "I am looking forward to meeting you."
    assert body["answer"] == "meeting" and body["distractors"] == ["meet"]
    assert "addNote" not in fake_anki["calls"]


def test_grammar_card_without_a_mistake_lets_the_gateway_make_all_options(fake_anki, gateway):
    anki_service.add_grammar_card(GrammarCardRequest(sentence="It is a book.", answer="a", mistake="  "))
    assert gateway[0][1]["distractors"] == []


def test_grammar_duplicate_never_reaches_gateway(fake_anki, gateway):
    fake_anki["dup"] = True
    res = anki_service.add_grammar_card(GrammarCardRequest(sentence="I agree.", answer="agree", mistake="agrees"))
    assert res.success and res.duplicate
    assert gateway == []


def test_gateway_refusal_reason_is_shown(fake_anki, monkeypatch):
    class Resp:
        status_code = 400

        def raise_for_status(self):
            raise anki_module.requests.exceptions.HTTPError("400 Client Error: Bad Request")

        def json(self):
            return {"detail": "정답 'the'이(가) 문장에 2번 나옵니다."}

    monkeypatch.setattr(anki_module.requests, "post", lambda url, json, timeout: Resp())
    res = anki_service.add_grammar_card(GrammarCardRequest(sentence="The cat saw the dog.", answer="the", mistake="a"))
    assert not res.success and "2번 나옵니다" in res.error
